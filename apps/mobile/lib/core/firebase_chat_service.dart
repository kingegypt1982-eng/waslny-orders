/// Message type enum for chat messages
enum MessageType { text, image, file, system }

/// Image message model for Firebase Storage
class ImageMessage {
  final String imageId;
  final String downloadUrl;
  final String filePath;
  final String caption;
  final DateTime createdAt;

  ImageMessage({
    required this.imageId,
    required this.downloadUrl,
    required this.filePath,
    this.caption = '',
    DateTime? createdAt,
  }) : createdAt = createdAt ?? DateTime.now();

  Map<String, dynamic> toMap() {
    return {
      'imageId': imageId,
      'downloadUrl': downloadUrl,
      'filePath': filePath,
      'caption': caption,
      'createdAt': createdAt.toIso8601String(),
    };
  }

  factory ImageMessage.fromMap(Map<dynamic, dynamic> map, String imageId) {
    return ImageMessage(
      imageId: imageId,
      downloadUrl: map['downloadUrl']?.toString() ?? '',
      filePath: map['filePath']?.toString() ?? '',
      caption: map['caption']?.toString() ?? '',
      createdAt: map['createdAt'] != null
          ? DateTime.parse(map['createdAt'].toString())
          : DateTime.now(),
    );
  }
}

/// Chat message model using Firebase Realtime Database
class ChatMessage {
  final String id;
  final String senderId;
  final String receiverId;
  final String role;
  final String content;
  final MessageType type;
  final DateTime createdAt;
  final String? readBy;
  final DateTime? readAt;
  final String? orderId;

  ChatMessage({
    required this.id,
    required this.senderId,
    required this.receiverId,
    required this.role,
    required this.content,
    required this.type,
    required this.createdAt,
    this.readBy,
    this.readAt,
    this.orderId,
  });

  factory ChatMessage.fromMap(Map<dynamic, dynamic> map, String id) {
    return ChatMessage(
      id: id,
      senderId: map['senderId']?.toString() ?? '',
      receiverId: map['receiverId']?.toString() ?? '',
      role: map['role']?.toString() ?? 'CLIENT',
      content: map['content']?.toString() ?? '',
      type: _stringToMessageType(map['type']?.toString() ?? 'text'),
      createdAt: map['createdAt'] != null
          ? DateTime.parse(map['createdAt'].toString())
          : DateTime.now(),
      readBy: map['readBy']?.toString(),
      readAt: map['readAt'] != null ? DateTime.parse(map['readAt'].toString()) : null,
      orderId: map['orderId']?.toString(),
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'senderId': senderId,
      'receiverId': receiverId,
      'role': role,
      'content': content,
      'type': type.toString().split('.').last,
      'createdAt': createdAt.toIso8601String(),
      'readBy': readBy,
      'readAt': readAt?.toIso8601String(),
      'orderId': orderId,
    };
  }

  static MessageType _stringToMessageType(String type) {
    switch (type) {
      case 'image':
        return MessageType.image;
      case 'file':
        return MessageType.file;
      case 'system':
        return MessageType.system;
      default:
        return MessageType.text;
    }
  }
}

/// Firebase Chat Service using Realtime Database and custom tokens.
///
/// Security: Uses Firebase Custom Tokens generated by the backend API.
/// The backend associates each token with a Waslny user identity and role.
/// Chat data is stored in the order's chat namespace and is only accessible
/// to the client, captain, and admins via Firebase Security Rules.
class FirebaseChatService {
  final FirebaseDatabase _db = FirebaseDatabase.instance;
  final FirebaseAuth _auth = FirebaseAuth.instance;
  final FirebaseStorage _storage = FirebaseStorage.instance;

  /// API base URL - can be overridden via constructor or environment variable.
  /// Default: https://api.waslny.com (or your dev/staging endpoint)
  final String _apiBaseUrl;

  FirebaseChatService({String? apiBaseUrl})
      : _apiBaseUrl = apiBaseUrl ??
            const String.fromEnvironment(
              'API_BASE_URL',
              defaultValue: 'http://10.0.2.2:3000', // Android emulator default
            );

  /// Initialize Firebase with a custom token from the backend.
  /// This must be called after Firebase.initializeApp() in main().
  ///
  /// Returns true if Firebase was successfully authenticated, false otherwise.
  Future<bool> signInWithCustomToken() async {
    final currentUser = _auth.currentUser;
    if (currentUser != null) {
      // Already signed in, but let's verify the token is still valid
      try {
        await currentUser.getIdToken(true);
        return true;
      } catch (e) {
        // Token expired, need to refresh
      }
    }

    try {
      // Get custom token from backend API
      final token = await _fetchCustomToken();
      if (token == null) {
        return false;
      }

      // Sign in with the custom token
      await _auth.signInWithCustomToken(token);
      return true;
    } catch (e) {
      // Failed to sign in - chat features will be disabled
      return false;
    }
  }

  /// Fetch a Firebase Custom Token from the backend API.
  /// The backend validates the user's session and generates a token
  /// with appropriate claims (role, waslny_user_id).
  Future<String?> _fetchCustomToken() async {
    try {
      // Get the current session/cookie from the webview or shared preferences
      // This assumes the user is already authenticated via the Waslny API
      final sessionCookie = await _getSessionCookie();
      if (sessionCookie == null) {
        return null;
      }

      final response = await http.get(
        Uri.parse('$_apiBaseUrl/api/v1/firebase/token'),
        headers: {
          'Content-Type': 'application/json',
          'Cookie': sessionCookie,
        },
      );

      if (response.statusCode == 200) {
        final data = _parseJson(response.body);
        if (data != null && data['customToken'] != null) {
          return data['customToken'] as String;
        }
        if (data != null && data['error'] != null) {
          // Chat is disabled or not configured
          return null;
        }
      }
      return null;
    } catch (e) {
      return null;
    }
  }

  /// Retrieve the session cookie from shared preferences.
  /// This should be set when the user logs in via the API.
  Future<String?> _getSessionCookie() async {
    // The session cookie is typically stored when the user logs in
    // This is a placeholder - implementation depends on how session auth is handled
    final prefs = await SharedPreferences.getInstance();
    return prefs.getString('session_cookie');
  }

  /// Simple JSON parse helper that handles errors gracefully.
  Map<String, dynamic>? _parseJson(String responseBody) {
    try {
      final data = <String, dynamic>{};
      final parts = responseBody.split('}');
      for (final part in parts) {
        final colonIndex = part.indexOf(':');
        if (colonIndex != -1) {
          final key = part.substring(0, colonIndex).replaceAll(RegExp(r'"'), '');
          final value = part.substring(colonIndex + 1).trim();
          data[key] = value;
        }
      }
      return data;
    } catch (e) {
      return null;
    }
  }

  /// Get the current order's chat meta data.
  /// Used to verify the user has access to this order's chat.
  Future<Map<String, dynamic>?> getOrderChatMeta(String orderId) async {
    try {
      final snapshot = await _db.ref('chats/meta/$orderId').get();
      if (snapshot.exists) {
        return Map<String, dynamic>.from(snapshot.value as Map);
      }
      return null;
    } catch (e) {
      return null;
    }
  }

  /// Send a new message to the order's chat.
  ///
  /// Security: Messages are stored under `chats/messages/{orderId}/{messageId}`.
  /// Firebase Security Rules ensure only participants (client/captain) can write.
  Future<String?> sendMessage({
    required String content,
    required String orderId,
    MessageType type = MessageType.text,
    File? imageFile,
  }) async {
    final currentUser = _auth.currentUser;
    if (currentUser == null) {
      return null;
    }

    // Verify user has access to this order's chat
    final chatMeta = await getOrderChatMeta(orderId);
    if (chatMeta == null || chatMeta['status'] != 'ACTIVE') {
      return null;
    }

    final senderId = currentUser.uid;
    final messageId = _db.ref('chats/messages/$orderId').push().key;
    if (messageId == null) {
      return null;
    }

    String finalContent = content;
    MessageType finalType = type;

    // Handle image upload if provided
    if (imageFile != null && type == MessageType.image) {
      try {
        final imageId = DateTime.now().millisecondsSinceEpoch.toString();
        final imageRef = _storage.ref().child('chat_images/$orderId/$imageId');
        await imageRef.putFile(imageFile);
        final downloadUrl = await imageRef.getDownloadURL();

        // Store image metadata
        final imageMsg = ImageMessage(
          imageId: imageId,
          downloadUrl: downloadUrl,
          filePath: 'chat_images/$orderId/$imageId',
        );
        await _db.ref('chats/images/$orderId/$imageId').set(imageMsg.toMap());

        finalContent = downloadUrl;
        finalType = MessageType.image;
      } catch (e) {
        return null;
      }
    }

    // Get receiver ID from chat meta
    final isAdmin = chatMeta['clientId'] != senderId;
    final receiverId = isAdmin
        ? chatMeta['clientId']
        : chatMeta['captainId'];

    final message = ChatMessage(
      id: messageId,
      senderId: senderId,
      receiverId: receiverId ?? '',
      role: chatMeta['clientId'] == senderId ? 'CLIENT' : 'CAPTAIN',
      content: finalContent,
      type: finalType,
      createdAt: DateTime.now(),
      orderId: orderId,
    );

    await _db.ref('chats/messages/$orderId/$messageId').set(message.toMap());
    return messageId;
  }

  /// Listen to messages for a specific order (real-time stream).
  Stream<List<ChatMessage>> listenMessages(String orderId) {
    return _db.ref('chats/messages/$orderId').onValue.map((event) {
      final data = event.snapshot.value;
      if (data == null) return <ChatMessage>[];

      final Map<dynamic, dynamic> map = data as Map<dynamic, dynamic>;
      return map.entries.map((entry) {
        final value = entry.value as Map<dynamic, dynamic>;
        return ChatMessage.fromMap(value, entry.key.toString());
      }).toList(growable: false)
        ..sort((a, b) => a.createdAt.compareTo(b.createdAt));
    });
  }

  /// Mark a message as read.
  Future<void> markAsRead(String orderId, String messageId) async {
    final currentUser = _auth.currentUser;
    if (currentUser == null) return;

    await _db.ref('chats/messages/$orderId/$messageId/readBy').set(currentUser.uid);
    await _db.ref('chats/messages/$orderId/$messageId/readAt')
        .set(DateTime.now().toIso8601String());
  }

  /// Get current user's UID.
  String? getCurrentUserId() {
    return _auth.currentUser?.uid;
  }

  /// Check if user is authenticated via Firebase.
  bool get isAuthenticated => _auth.currentUser != null;

  /// Close the chat for an order (called when order is completed/cancelled).
  Future<void> closeChat(String orderId) async {
    final chatMeta = await getOrderChatMeta(orderId);
    if (chatMeta == null) return;

    await _db.ref('chats/meta/$orderId').update({
      'status': 'CLOSED',
      'closedAt': DateTime.now().toIso8601String(),
    });
  }
}

